import type { DiagramBlock, DiagramElement } from '../shared/protocol';
import { declarationKinds } from './kinds';
import { codeLines } from './syntax';

/** Families whose containers are brace blocks in the source, so membership is where a declaration is written. */

const descendantsOf = (block: DiagramBlock, id: string): Set<string> => {
  const ids = new Set([id]);
  for (let grew = true; grew;) {
    grew = false;
    for (const element of block.elements) if (element.parentId && ids.has(element.parentId) && !ids.has(element.id)) { ids.add(element.id); grew = true; }
  }
  return ids;
};

const ancestorsOf = (block: DiagramBlock, element: DiagramElement): DiagramElement[] => {
  const chain: DiagramElement[] = [];
  for (let parent = block.elements.find(item => item.id === element.parentId); parent && !chain.includes(parent); parent = block.elements.find(item => item.id === parent!.parentId)) chain.push(parent);
  return chain;
};

/**
 * Why this element cannot change container, or undefined when it can. Regions of a concurrent state
 * are separators inside one body, and a namespace changes the full names its members are known by.
 */
function immovable(block: DiagramBlock, element: DiagramElement): string | undefined {
  if (!declarationKinds.has(block.kind) || block.meta?.legacy || !block.graphical) return 'This diagram does not nest elements in source blocks. Edit the structure in the source panel.';
  if (element.implicit) return 'This element is only mentioned by a relationship. Declare it in the source before moving it into a container.';
  if (element.meta?.editable === false || element.meta?.procedure) return 'This element is generated by the source structure and cannot be moved on its own.';
  const parents = ancestorsOf(block, element);
  if (parents.some(parent => parent.kind === 'state-region')) return 'States in concurrent regions keep their region. Move them in the source panel.';
  if (parents.some(parent => parent.kind === 'namespace') || element.kind === 'namespace') return 'Namespaces change the names of their members. Move elements across namespaces in the source panel.';
}

/** Whether a container accepts moved declarations: a brace body of its own, not split into regions. */
const accepts = (block: DiagramBlock, code: string[], container: DiagramElement) => Boolean(container.meta?.container) && container.meta?.editable !== false && !container.implicit
  && container.kind !== 'namespace' && container.endLine > container.startLine && code[container.endLine]?.trim() === '}'
  && !block.elements.some(child => child.parentId === container.id && child.kind === 'state-region') && !ancestorsOf(block, container).some(parent => parent.kind === 'state-region' || parent.kind === 'namespace');

/**
 * The containers this element may be moved into (its current one included), or undefined when it
 * cannot move at all. `source` is the whole document the block was parsed from.
 */
export function containerTargets(source: string, block: DiagramBlock, elementId: string): DiagramElement[] | undefined {
  const element = block.elements.find(item => item.id === elementId);
  if (!element || immovable(block, element)) return undefined;
  const code = codeLines(source), excluded = descendantsOf(block, elementId);
  return block.elements.filter(container => !excluded.has(container.id) && accepts(block, code, container));
}

/**
 * Cut an element's declaration, with its body, its contents and the comment lines directly above it,
 * and write it inside another container's braces or at block level. Relationships and member
 * statements refer to aliases, which do not change, so they stay where they are.
 */
export function moveToContainer(source: string, block: DiagramBlock, elementId: string, parentId: string | undefined): string {
  const element = block.elements.find(item => item.id === elementId);
  if (!element) throw new Error('This element no longer exists. Try the edit again on the current diagram.');
  const reason = immovable(block, element);
  if (reason) throw new Error(reason);
  if ((element.parentId ?? undefined) === (parentId ?? undefined)) return source;
  const eol = source.includes('\r\n') ? '\r\n' : '\n';
  const lines = source.split(/\r?\n/), code = codeLines(source);
  const indentOf = (line: number) => lines[line].match(/^\s*/)![0];
  let insertAt: number, indent: string;
  if (parentId) {
    const target = block.elements.find(item => item.id === parentId);
    if (!target) throw new Error('This container no longer exists. Try the move again on the current diagram.');
    if (descendantsOf(block, elementId).has(parentId)) throw new Error('An element cannot be moved into itself or into one of its own contents.');
    if (!accepts(block, code, target)) throw new Error(target.meta?.container ? 'This container has no block to hold the element, or is split into regions. Use the source editor.' : 'Only packages, nodes, composite states and similar containers can hold other elements.');
    insertAt = target.endLine;
    const child = block.elements.find(item => item.parentId === target.id && !item.implicit && item.startLine > target.startLine && item.id !== elementId);
    indent = child ? indentOf(child.startLine) : indentOf(target.startLine) + '  ';
  } else {
    const outermost = ancestorsOf(block, element).at(-1)!;
    // Above the outermost container, so nothing inside it now refers to a declaration written later.
    insertAt = leadingComments(lines, code, outermost.startLine, block.startLine);
    indent = indentOf(outermost.startLine);
  }
  const first = leadingComments(lines, code, element.startLine, element.parentId ? block.elements.find(item => item.id === element.parentId)!.startLine : block.startLine);
  const from = indentOf(element.startLine);
  const moved = lines.slice(first, element.endLine + 1).map(line => !line.trim() ? '' : line.startsWith(from) ? indent + line.slice(from.length) : indent + line.trimStart());
  const before = lines.slice(0, insertAt).filter((_, index) => index < first || index > element.endLine);
  const after = lines.slice(insertAt).filter((_, offset) => insertAt + offset < first || insertAt + offset > element.endLine);
  return [...before, ...moved, ...after].join(eol);
}

/** The first of the comment-only lines directly above a line; a blank line ends a comment's attachment. */
function leadingComments(lines: string[], code: string[], line: number, floor: number): number {
  let first = line;
  while (first - 1 > floor && lines[first - 1].trim() && !code[first - 1].trim()) first--;
  return first;
}
